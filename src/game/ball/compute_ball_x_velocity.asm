sub_compute_ball_x_velocity:
	ld a,c
	add a,a
	ld c,a
	ld b,000h
	ld hl,table_ball_x_vel_pointers
	add hl,bc
	ld e,(hl)
	inc hl
	ld d,(hl)
	ld a,(state.ball_hit_type)
	add a,a
	ld c,a
	add a,a
	ld b,a
	add a,a
	add a,a
	add a,c
	add a,b
	ld c,a
	ld a,(ix + entity_t.render_facing_dir)
	sub 00bh
	jr nc,@skip_add
	add a,00bh
@skip_add:
	add a,a
	add a,c
	ld c,a
	ld b,000h
	ex de,hl
	add hl,bc
	ld e,(hl)
	inc hl
	ld d,(hl)
	ld a,(state.last_hitter)
	and 001h
	jr z,@store_vel
	xor a
	ld hl,0
	sbc hl,de
	ex de,hl
@store_vel:
	ld (ball.x_vel),de
	ret

